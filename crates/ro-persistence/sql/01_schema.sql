-- Schema initialization for Project Metaling persistence.
-- Creates baseline tables for accounts, characters and inventories.
-- Tables use CREATE TABLE IF NOT EXISTS, so a column added to an existing table needs its own
-- guarded ALTER TABLE (see unique_item_counter below), or existing databases never get it.

-- The whole file runs as one implicit transaction. Serialize concurrent runs (servers or tests
-- starting together): the IF NOT EXISTS index checks take share locks, and two runs that both
-- then reach an ALTER TABLE would deadlock.
SELECT pg_advisory_xact_lock(4206910001);

CREATE TABLE IF NOT EXISTS accounts (
    account_id      INT GENERATED BY DEFAULT AS IDENTITY (START WITH 2000000) PRIMARY KEY,
    username        VARCHAR(23) NOT NULL UNIQUE,
    password_hash   VARCHAR(128) NOT NULL,
    sex             SMALLINT NOT NULL DEFAULT 1,
    email           VARCHAR(39) NOT NULL DEFAULT 'a@a.com',
    group_id        INT NOT NULL DEFAULT 0,
    state           SMALLINT NOT NULL DEFAULT 0,
    unban_time      BIGINT,
    expiration_time BIGINT
);

CREATE TABLE IF NOT EXISTS characters (
    char_id       INT GENERATED BY DEFAULT AS IDENTITY (START WITH 150000) PRIMARY KEY,
    account_id    INT NOT NULL REFERENCES accounts(account_id) ON DELETE CASCADE,
    slot          SMALLINT NOT NULL,
    name          VARCHAR(24) NOT NULL UNIQUE,
    sex           SMALLINT NOT NULL,
    job_class     SMALLINT NOT NULL DEFAULT 0,
    base_level    SMALLINT NOT NULL DEFAULT 1,
    job_level     SMALLINT NOT NULL DEFAULT 1,
    base_exp      BIGINT NOT NULL DEFAULT 0,
    job_exp       BIGINT NOT NULL DEFAULT 0,
    zeny          INT NOT NULL DEFAULT 0,
    str           SMALLINT NOT NULL DEFAULT 1,
    agi           SMALLINT NOT NULL DEFAULT 1,
    vit           SMALLINT NOT NULL DEFAULT 1,
    int_stat      SMALLINT NOT NULL DEFAULT 1,
    dex           SMALLINT NOT NULL DEFAULT 1,
    luk           SMALLINT NOT NULL DEFAULT 1,
    max_hp        INT NOT NULL DEFAULT 40,
    hp            INT NOT NULL DEFAULT 40,
    max_sp        INT NOT NULL DEFAULT 11,
    sp            INT NOT NULL DEFAULT 11,
    status_point  SMALLINT NOT NULL DEFAULT 48,
    skill_point   SMALLINT NOT NULL DEFAULT 0,
    hair_style    SMALLINT NOT NULL DEFAULT 1,
    hair_color    SMALLINT NOT NULL DEFAULT 0,
    clothes_color SMALLINT NOT NULL DEFAULT 0,
    weapon_type   INT NOT NULL DEFAULT 0,
    shield_view   INT NOT NULL DEFAULT 0,
    head_top_view INT NOT NULL DEFAULT 0,
    head_mid_view INT NOT NULL DEFAULT 0,
    head_bot_view INT NOT NULL DEFAULT 0,
    robe_view     INT NOT NULL DEFAULT 0,
    last_map      VARCHAR(64) NOT NULL DEFAULT 'prontera.gat',
    last_x        SMALLINT NOT NULL DEFAULT 156,
    last_y        SMALLINT NOT NULL DEFAULT 191,
    last_dir      SMALLINT NOT NULL DEFAULT 0,
    save_map      VARCHAR(64) NOT NULL DEFAULT 'prontera.gat',
    save_x        SMALLINT NOT NULL DEFAULT 156,
    save_y        SMALLINT NOT NULL DEFAULT 191,
    delete_date   BIGINT,
    UNIQUE (account_id, slot)
) WITH (fillfactor = 75);

CREATE INDEX IF NOT EXISTS idx_characters_account_id ON characters(account_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_characters_name_lower ON characters(LOWER(name));

-- Next unique_id counter: unique_id = (char_id << 32) | counter.
-- ALTER TABLE takes an exclusive lock even when the column exists, which deadlocks with
-- concurrent character writes; only run it when the column is missing.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'characters' AND column_name = 'unique_item_counter'
    ) THEN
        ALTER TABLE characters ADD COLUMN unique_item_counter BIGINT NOT NULL DEFAULT 0;
    END IF;
END $$;

-- Char-select looks (equipment): the weapon column holds the weapon type, not a view, so
-- databases from before it get `weapon_view` renamed; `robe_view` is new.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'characters' AND column_name = 'weapon_view'
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'characters' AND column_name = 'weapon_type'
    ) THEN
        ALTER TABLE characters RENAME COLUMN weapon_view TO weapon_type;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'characters' AND column_name = 'robe_view'
    ) THEN
        ALTER TABLE characters ADD COLUMN robe_view INT NOT NULL DEFAULT 0;
    END IF;
END $$;

-- One row per inventory item. Rows load in id order, so slots compact on load.
-- u32 fields are BIGINT; unique_id (u64) is stored bit-cast into BIGINT.
CREATE TABLE IF NOT EXISTS inventory (
    id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    char_id       INT NOT NULL REFERENCES characters(char_id) ON DELETE CASCADE,
    nameid        BIGINT NOT NULL,
    amount        INT NOT NULL,
    equip         BIGINT NOT NULL DEFAULT 0,
    identify      SMALLINT NOT NULL DEFAULT 0,
    refine        SMALLINT NOT NULL DEFAULT 0,
    attribute     SMALLINT NOT NULL DEFAULT 0,
    card0         BIGINT NOT NULL DEFAULT 0,
    card1         BIGINT NOT NULL DEFAULT 0,
    card2         BIGINT NOT NULL DEFAULT 0,
    card3         BIGINT NOT NULL DEFAULT 0,
    option_id0    SMALLINT NOT NULL DEFAULT 0,
    option_val0   SMALLINT NOT NULL DEFAULT 0,
    option_parm0  SMALLINT NOT NULL DEFAULT 0,
    option_id1    SMALLINT NOT NULL DEFAULT 0,
    option_val1   SMALLINT NOT NULL DEFAULT 0,
    option_parm1  SMALLINT NOT NULL DEFAULT 0,
    option_id2    SMALLINT NOT NULL DEFAULT 0,
    option_val2   SMALLINT NOT NULL DEFAULT 0,
    option_parm2  SMALLINT NOT NULL DEFAULT 0,
    option_id3    SMALLINT NOT NULL DEFAULT 0,
    option_val3   SMALLINT NOT NULL DEFAULT 0,
    option_parm3  SMALLINT NOT NULL DEFAULT 0,
    option_id4    SMALLINT NOT NULL DEFAULT 0,
    option_val4   SMALLINT NOT NULL DEFAULT 0,
    option_parm4  SMALLINT NOT NULL DEFAULT 0,
    expire_time   BIGINT NOT NULL DEFAULT 0,
    favorite      SMALLINT NOT NULL DEFAULT 0,
    bound         SMALLINT NOT NULL DEFAULT 0,
    unique_id     BIGINT NOT NULL DEFAULT 0,
    equip_switch  BIGINT NOT NULL DEFAULT 0,
    enchantgrade  SMALLINT NOT NULL DEFAULT 0
);

-- (char_id, id) serves the load's ORDER BY id without a sort.
CREATE INDEX IF NOT EXISTS idx_inventory_char_id_id ON inventory(char_id, id);
